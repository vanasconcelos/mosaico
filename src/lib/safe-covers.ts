/**
 * Único ponto da aplicação que decide qual imagem pública mostrar pra um
 * template, pra visitantes sem acesso pago. Desde a B4.4, todo slug real
 * do catálogo está em `SLUGS_COM_CAPA_DEDICADA` — então, na prática,
 * qualquer template de verdade cai no primeiro branch. O segundo branch
 * (retornar `null`) nunca aponta pra `public/templates/`: é a falha seg
 * ura pra um slug que não existe no catálogo, ou que existir mas ainda
 * não tiver sido cadastrado aqui (ex.: um template novo adicionado em
 * `templates.ts` sem atualizar esta lista) — nesses casos, nunca expor o
 * arquivo original; quem chama já trata `null` como "sem capa disponível"
 * (grids filtram, `TemplatePreview` mostra um placeholder).
 *
 * `slug` pode ser `null` (ex.: placeholders decorativos sem template
 * real por trás) — cai no mesmo caminho de falha segura.
 */
export function resolveSafeCoverUrl(slug: string | null | undefined): string | null {
  if (slug && SLUGS_COM_CAPA_DEDICADA.has(slug)) {
    return `/templates-capas/${slug}.jpg`;
  }
  return null;
}
